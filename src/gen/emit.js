// Arranged voices -> rasterklang-dsl source. Every distinct bar
// becomes a named proportional pattern; each voice plays them as a
// per-bar orderlist `<[$a] [$b] ...>`, the shape rasterklang-cycles'
// tracker importer uses, so the result opens in cycles and the DAW.

import { instrumentBlocks } from './instruments.js';
import { KEY_NAMES } from './theory.js';

function lerp(a, b, t) {
  return Math.round(a + (b - a) * t);
}

export function emitDsl(plan, arrangement, title) {
  const { voices } = arrangement;
  const { style } = plan;
  const lines = [];
  lines.push(`; ${title}`);
  lines.push(`; ${style.name}, ${KEY_NAMES[plan.keyRoot]} ${plan.mode}, ${plan.meter.id}, ${plan.bpm.toFixed(1)} bpm, ${plan.totalBars} bars`);
  lines.push(`; generated by rasterklang-compose ${plan.version}, seed ${plan.seedNumber ?? plan.seed}`);
  lines.push('');
  lines.push(`speed ${plan.speed} meter ${plan.meter.beats}/${plan.meter.unit}`);
  lines.push('');

  const used = new Set();
  const defaults = voices.map((bars) => {
    for (const bar of bars) for (const c of bar) if (c.inst) return c.inst;
    return null;
  });
  for (const bars of voices) for (const bar of bars) for (const c of bar) if (c.inst) used.add(c.inst);
  lines.push(instrumentBlocks([...used], plan.sound, plan.speed));
  lines.push('');

  const voiceLines = [];
  voices.forEach((bars, v) => {
    const noteNames = new Map();
    const instNames = new Map();
    const noteOrder = [];
    const instOrder = [];
    const distinctInst = new Set();
    for (const bar of bars) for (const c of bar) if (c.inst) distinctInst.add(c.inst);
    for (const bar of bars) {
      const toks = bar.map((c) => c.tok);
      if (toks[0] === '_') toks[0] = '~'; // a bar cannot start with a hold
      const text = toks.join(' ');
      if (!noteNames.has(text)) {
        const name = `v${v}n${noteNames.size}`;
        noteNames.set(text, name);
        lines.push(`pattern ${name} = "${text}"`);
      }
      noteOrder.push(`[$${noteNames.get(text)}]`);
      if (distinctInst.size > 1) {
        const itext = bar.map((c) => c.inst || '~').join(' ');
        if (!instNames.has(itext)) {
          const name = `v${v}i${instNames.size}`;
          instNames.set(itext, name);
          lines.push(`pattern ${name} = "${itext}"`);
        }
        instOrder.push(`[$${instNames.get(itext)}]`);
      }
    }
    const def = defaults[v] || 'lead';
    voiceLines.push(`voice ${v} ${def}`);
    voiceLines.push(`  notes "<${noteOrder.join(' ')}>"`);
    if (instOrder.length) voiceLines.push(`  insts "<${instOrder.join(' ')}>"`);
    // ring modulation and hard sync are voice fields: on for the steps the
    // ring and sync leads play
    for (const field of ['ring', 'sync']) {
      const uses = (inst) => inst === field || inst === `${field}bend`;
      if (![...distinctInst].some(uses)) continue;
      const names = new Map();
      const order = [];
      let cur = defaults[v];
      for (const bar of bars) {
        const text = bar.map((c) => { if (c.inst) cur = c.inst; return uses(cur) ? '1' : '0'; }).join(' ');
        if (!names.has(text)) {
          const name = `v${v}${field[0]}${names.size}`;
          names.set(text, name);
          lines.push(`pattern ${name} = "${text}"`);
        }
        order.push(`[$${names.get(text)}]`);
      }
      voiceLines.push(`  ${field} "<${order.join(' ')}>"`);
    }
    voiceLines.push('end');
  });
  lines.push('');
  lines.push(...voiceLines);
  lines.push('');

  // Filter: the bass voice runs through a low-pass whose cutoff follows the
  // section's energy curve, or opens, closes or wobbles as the brief says.
  const [cLo, cHi] = style.filter?.cutoff || [500, 1600];
  const cut = [];
  for (const s of plan.sections) {
    const end = s.startBar + s.bars;
    const c0 = lerp(cLo, cHi, s.energy);
    const c1 = lerp(cLo, cHi, s.energyEnd ?? s.energy);
    const shape = s.filter || (s.textureDef.filter === 'open' ? 'open' : 'follow');
    let expr;
    if (shape === 'open') expr = `saw ${Math.min(c0, cLo + 80)}..${Math.max(c1, c0 + 200)} / ${s.bars}`;
    else if (shape === 'close') expr = `saw ${Math.max(c0, c1 + 200)}..${Math.min(c1, cLo + 80)} / ${s.bars}`;
    else if (shape === 'wobble') expr = `sine ${Math.max(cLo, c0 - 350)}..${Math.min(2047, c0 + 350)} * 1`;
    else if (shape === 'follow' && Math.abs(c1 - c0) >= 40 && s.bars > 1) {
      // a stepped ramp, one value per bar: audible movement, few register
      // writes (keeps the .sid small)
      for (let b = 0; b < s.bars; b += 1) {
        const v = Math.round(c0 + ((c1 - c0) * b) / (s.bars - 1));
        cut.push(`    < ${s.startBar + b + 1} : sine ${v}..${v} / 1`);
      }
      continue;
    } else expr = `sine ${c0}..${c0} / 1`;
    cut.push(`    < ${end} : ${expr}`);
  }
  // routing per bar from the arrangement, runs of equal bars merged
  const route = [];
  const routes = arrangement.routes;
  for (let b = 0; b < routes.length; b += 1) {
    const r = routes[b].length ? routes[b].join(' ') : '0';
    const nextR = b + 1 < routes.length ? (routes[b + 1].length ? routes[b + 1].join(' ') : '0') : null;
    if (r !== nextR) route.push(`    < ${b + 1} : ${r}`);
  }
  cut[cut.length - 1] = cut[cut.length - 1].replace(/< \d+ :/, 'else :');
  route[route.length - 1] = route[route.length - 1].replace(/< \d+ :/, 'else :');
  lines.push('filter');
  lines.push('  cutoff switch bar', ...cut);
  lines.push(`  resonance ${style.filter?.resonance ?? 9}`);
  lines.push('  mode lowpass');
  lines.push('  route switch bar', ...route);
  lines.push('end');
  return lines.join('\n') + '\n';
}
